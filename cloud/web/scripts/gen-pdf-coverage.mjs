// Regenerates lib/export/pdf-coverage.ts: the code points every bundled
// pdfmake Roboto face can draw (regular, medium, italic, medium italic).
// The PDF export swaps anything outside this set (emoji, Hebrew, Arabic, CJK…)
// for a placeholder instead of printing blanks. Re-run after a pdfmake upgrade:
//   node scripts/gen-pdf-coverage.mjs
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const req = createRequire(path.join(root, "package.json"));
const vfsMod = req("pdfmake/build/vfs_fonts.js");
const vfs = vfsMod.pdfMake?.vfs ?? vfsMod.vfs ?? vfsMod;
const fontkit = req("@foliojs-fork/fontkit");
const faces = ["Roboto-Regular.ttf", "Roboto-Medium.ttf", "Roboto-Italic.ttf", "Roboto-MediumItalic.ttf"].map((f) =>
  fontkit.create(Buffer.from(vfs[f], "base64"))
);

const ranges = [];
let start = -1;
for (let cp = 0x20; cp <= 0x110000; cp++) {
  const ok = cp <= 0x10ffff && faces.every((f) => f.hasGlyphForCodePoint(cp));
  if (ok && start < 0) start = cp;
  if (!ok && start >= 0) {
    ranges.push([start, cp - 1]);
    start = -1;
  }
}

const hex = (n) => "0x" + n.toString(16).toUpperCase();
const body = ranges.map(([a, b]) => `[${hex(a)}, ${hex(b)}]`).join(",\n  ");
const out = `// GENERATED by scripts/gen-pdf-coverage.mjs — do not edit by hand.
// Code points (inclusive ranges) that all four bundled pdfmake Roboto faces can draw.
export const PDF_FONT_RANGES: ReadonlyArray<readonly [number, number]> = [
  ${body},
];
`;
fs.writeFileSync(path.join(root, "lib/export/pdf-coverage.ts"), out);
console.log(`${ranges.length} ranges written`);
